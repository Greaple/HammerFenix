/**
 * Controller button icons (roadmap G.1): the Figma exports of `assets-src/pad-icons/` (README
 * there) cleaned into `src/game/gui/padIconData.ts`, so the screens can draw them in their own
 * colors.
 *
 * Each export is a frame of an icon sheet: the build drops the sheet's background rectangles,
 * makes the ids unique (several icons share a page in the help dialog) and replaces the icon's
 * light color with `__BODY__` and its dark one with `__INK__`.
 */
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { basename, join } from 'node:path';

const ROOT = join(import.meta.dirname, '..');
const SRC = join(ROOT, 'assets-src/pad-icons');
const OUT = join(ROOT, 'src/game/gui/padIconData.ts');

/** The icons' light color (the button), per sheet. */
const BODY = ['#D6E1F6', '#AFC1D1'];
/** Their dark color (letters and cut-outs, the sheet's background). */
const INK = ['#1C212A', '#1C1F2A'];

/** Icons in a 32 px frame with no margin: their button is the frame's height. */
const NO_MARGIN = new Set(['playstation/r2']);

interface Icon {
  svg: string;
  w: number;
  h: number;
  /** Height of the button inside the frame: 32 px frames keep a 4 px margin. */
  box: number;
}

function clean(file: string, prefix: string, key: string): Icon {
  let s = readFileSync(file, 'utf8').replace(/\r/g, '');
  const m = /<svg width="([\d.]+)" height="([\d.]+)"/.exec(s);
  if (!m) throw new Error(`${file}: no size`);
  const w = Number(m[1]);
  const h = Number(m[2]);
  // The frame's and the sheet's backgrounds
  s = s.replace(new RegExp(`<rect width="${w}" height="${h}" fill="#[0-9A-Fa-f]+"/>\\n?`), '');
  s = s.replace(
    /<rect width="[\d.]+" height="[\d.]+" transform="translate\([^)]*\)" fill="#[0-9A-Fa-f]+"\/>\n?/,
    '',
  );
  // Ids: the referenced ones made unique, the others (layer names) dropped
  const refs = new Set([...s.matchAll(/url\(#([^)]+)\)/g)].map((r) => r[1]));
  s = s.replace(/ id="([^"]*)"/g, (_, id: string) => (refs.has(id) ? ` id="${prefix}-${id}"` : ''));
  s = s.replace(/url\(#([^)]+)\)/g, (_, id: string) => `url(#${prefix}-${id})`);
  // Colors
  s = s.replace(/(fill|stroke)="(#[0-9A-Fa-f]{6})"/g, (all, attr: string, c: string) => {
    const u = c.toUpperCase();
    if (BODY.includes(u)) return `${attr}="__BODY__"`;
    if (INK.includes(u)) return `${attr}="__INK__"`;
    throw new Error(`${file}: unknown color ${c} (add it to BODY or INK)`);
  });
  s = s.replace(/\n+/g, '').replace(/>\s+</g, '><');
  return { svg: s, w, h, box: w === 32 && h === 32 && !NO_MARGIN.has(key) ? 24 : h };
}

const data: Record<string, Record<string, Icon>> = {};
let count = 0;
for (const layout of readdirSync(SRC, { withFileTypes: true })) {
  if (!layout.isDirectory()) continue;
  const icons: Record<string, Icon> = {};
  for (const f of readdirSync(join(SRC, layout.name)).sort()) {
    if (!f.endsWith('.svg')) continue;
    const button = basename(f, '.svg');
    icons[button] = clean(
      join(SRC, layout.name, f),
      `pad-${layout.name}-${button}`,
      `${layout.name}/${button}`,
    );
    count++;
  }
  if (Object.keys(icons).length > 0) data[layout.name] = icons;
}

const out = `// Generated by tools/build-pad-icons.ts from assets-src/pad-icons/: do not edit.

/** A controller button icon: SVG with \`__BODY__\` and \`__INK__\` colors, its size, the button's height. */
export interface PadIconData {
  svg: string;
  w: number;
  h: number;
  box: number;
}

/** Icons per controller layout, then per button. */
export const PAD_ICON_DATA: Record<string, Record<string, PadIconData>> = ${JSON.stringify(data, null, 2)};
`;
writeFileSync(OUT, out);
console.log(`pad icons: ${count} icons`);
