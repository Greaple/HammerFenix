/**
 * Offline play (roadmap 5.3, port addition): after `vite build`, writes `sw.js`, a service worker
 * that keeps every file of the build in the browser's cache, so the game starts and plays with
 * no network once it has been opened once. Only in the build: the dev server never caches.
 *
 * The cache name carries a hash of every file's content, so each deploy that changes a file
 * installs a fresh copy and deletes the old one. Left out: the original game for the Ruffle
 * side-by-side (`original-swf/`, a dev tool that also needs Ruffle from the network) and the
 * source maps.
 */
import { createHash } from 'node:crypto';
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join, relative, resolve, sep } from 'node:path';
import type { Plugin } from 'vite';

const SKIP = [/^original-swf\//, /\.map$/, /^sw\.js$/];

function walk(dir: string): string[] {
  return readdirSync(dir, { withFileTypes: true }).flatMap((e) =>
    e.isDirectory() ? walk(join(dir, e.name)) : [join(dir, e.name)],
  );
}

/** The files to cache, relative to the build folder, with `/` separators. */
export function offlineFiles(outDir: string): string[] {
  return walk(outDir)
    .map((f) => relative(outDir, f).split(sep).join('/'))
    .filter((f) => !SKIP.some((r) => r.test(f)))
    .sort();
}

/** The service worker. Paths are relative to it, so the build works from any sub-path. */
export function serviceWorker(version: string, files: string[]): string {
  return `// Generated by tools/vite-plugin-offline.ts: offline play (roadmap 5.3)
const CACHE = 'hammerfenix-${version}';
const FILES = ${JSON.stringify(['./', ...files])};

self.addEventListener('install', (event) => {
  event.waitUntil(
    caches
      .open(CACHE)
      .then((cache) => cache.addAll(FILES.map((f) => new Request(f, { cache: 'reload' }))))
      .then(() => self.skipWaiting()),
  );
});

self.addEventListener('activate', (event) => {
  event.waitUntil(
    caches
      .keys()
      .then((keys) =>
        Promise.all(
          keys
            .filter((k) => k.startsWith('hammerfenix-') && k !== CACHE)
            .map((k) => caches.delete(k)),
        ),
      )
      .then(() => self.clients.claim()),
  );
});

// The cache first, the network for anything else (the Ruffle side-by-side). A page opened
// offline gets the game's page whatever its address (\`?dev\`, \`index.html\`). Module scripts
// send an Origin header, and servers answer them with \`Vary: Origin\`: ignore it, or they miss.
self.addEventListener('fetch', (event) => {
  const req = event.request;
  if (req.method !== 'GET' || new URL(req.url).origin !== self.location.origin) return;
  event.respondWith(
    caches.open(CACHE).then(async (cache) => {
      const hit =
        req.mode === 'navigate'
          ? await cache.match('./', { ignoreVary: true })
          : await cache.match(req, { ignoreSearch: true, ignoreVary: true });
      return hit ?? fetch(req);
    }),
  );
});
`;
}

export function offline(): Plugin {
  let outDir = 'dist';
  return {
    name: 'hammerfenix-offline',
    apply: 'build',
    configResolved(config) {
      outDir = resolve(config.root, config.build.outDir);
    },
    closeBundle() {
      const files = offlineFiles(outDir);
      const hash = createHash('sha256');
      for (const f of files) {
        hash.update(f);
        hash.update(readFileSync(join(outDir, f)));
      }
      const version = hash.digest('hex').slice(0, 12);
      writeFileSync(join(outDir, 'sw.js'), serviceWorker(version, files));
      this.info?.(`offline: sw.js caches ${files.length} files (${version})`);
    },
  };
}
